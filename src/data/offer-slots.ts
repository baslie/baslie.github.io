// Настройки блока «Свободные слоты на неделе» (/offer/4).
// Занятость расчётная: зависит от номера недели и текущего времени, с записями не связана.

export interface OfferSlotsConfig {
  /** Слотов в неделю. Раскладываются по дням с понедельника: 20 → 3,3,3,3,3,3,2 */
  limit: number;
  /** Часовой пояс недели и подсветки «сегодня» */
  timeZone: string;
  /** Внутренние моменты слотов: на странице не показываются, нужны, чтобы слоты сегодняшнего дня «проходили» */
  times: string[];
  /** Доля слотов, которые за неделю так и остаются свободными (0–1) */
  neverBooked: number;
}

export const offerSlots: OfferSlotsConfig = {
  limit: 20,
  timeZone: 'Asia/Tomsk',
  times: ['11:00', '14:00', '17:00', '19:00'],
  neverBooked: 0.3,
};
